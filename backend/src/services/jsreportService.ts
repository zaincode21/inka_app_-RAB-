export async function renderFarmReportPdf(data: JsReportPayload): Promise<Buffer> {
  const reporter = await getReporter();
  const result = await reporter.render({
    template: {
      content: REPORT_TEMPLATE,
      engine: 'handlebars',
      recipe: 'chrome-pdf',
      chrome: {
        landscape: false,
        format: 'A4',
        printBackground: true,
        marginTop: '12mm',
        marginBottom: '12mm',
        marginLeft: '12mm',
        marginRight: '12mm',
      },
    },
    data,
  });
  return Buffer.from(result.content);
}
