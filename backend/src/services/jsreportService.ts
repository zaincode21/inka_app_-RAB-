import JsReport from '@jsreport/jsreport-core';
import JsReportHandlebars from '@jsreport/jsreport-handlebars';
import JsReportChromePdf from '@jsreport/jsreport-chrome-pdf';
import type { FarmReportInfo } from '../utils/reportExport.js';

type ReportColumn = { key: string; label: string };
type ReportRow = Record<string, string | number>;

export type JsReportPayload = {
  farm: FarmReportInfo;
  reportTitle: string;
  periodFrom: string;
  periodTo: string;
  generatedAt: string;
  generatedBy?: string;
  columns: ReportColumn[];
  rows: ReportRow[];
  summaryLines?: Array<{ label: string; value: string }>;
};

let reporterPromise: Promise<ReturnType<typeof JsReport>> | null = null;

async function getReporter() {
  if (!reporterPromise) {
    reporterPromise = (async () => {
      const reporter = JsReport({
        // Keep reporting embedded — no studio / separate HTTP port.
        loadConfig: false,
        autoSave: false,
      });
      reporter.use(JsReportHandlebars());
      reporter.use(
        JsReportChromePdf({
          launchOptions: {
            args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage'],
          },
        }),
      );
      await reporter.init();
      return reporter;
    })();
  }
  return reporterPromise;
}

